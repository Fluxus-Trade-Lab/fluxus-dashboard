describe('ZH_NAMES', () => {
  it('covers every known data name', () => {
    const missing = DATA_NAMES.filter(n => !(n in ZH_NAMES))
    expect(missing).toEqual([])
  })

  it('maps no two English names to the same Chinese name', () => {
    const values = Object.values(ZH_NAMES)
    expect(new Set(values).size).toBe(values.length)
  })

  it('every value contains a Han character', () => {
    const bad = Object.entries(ZH_NAMES).filter(([, v]) => !/\p{Script=Han}/u.test(v))
    expect(bad).toEqual([])
  })
})

describe('dataName', () => {
  it('falls back to the English name when unknown', () => {
    expect(dataName('Unknown Theme', 'zh')).toBe('Unknown Theme')
  })
  it('returns English unchanged in en mode', () => {
    expect(dataName('Genomics', 'en')).toBe('Genomics')
  })
  it('translates a known name in zh mode', () => {
    expect(dataName('Genomics', 'zh')).toBe('基因组学')
  })
})
